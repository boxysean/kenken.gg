export function glyphFor(char: string): Glyph {
  if (!Object.prototype.hasOwnProperty.call(GLYPHS, char)) {
    throw new Error(`glyphFor: no glyph for ${JSON.stringify(char)}`);
  }
  return GLYPHS[char as GlyphChar];
}
